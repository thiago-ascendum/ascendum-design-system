"""08_figma_docs.py [--images DIR]: brings the Figma documentation into Storybook.

1. Runs pipeline/08_figma_docs.js in Figma (read only) and saves build/figma-docs.json: the words of every
   "<Component> / Documentation" frame (header, rows of named variants, side blocks, footer). Coded components
   draw their Storybook page from it, with the live component in every variant.
2. For each component or pattern that has no code yet, it writes a page with the Figma documentation frame
   as an image (stories/figma-only/), so Storybook has a page for every Figma page. When a component gets
   code, its generated page is removed and the coded page takes over.

Images come from the Figma plugin export, or from --images DIR: PNGs named by documentation frame id
("1104_2566.png"), for example exported through the Figma REST API when the plugin cannot open the file.
Needs: python3 with Pillow. Env: BUX (path to bux.sh), FIGMA_FILE.
"""
import base64, io, json, os, re, subprocess, sys
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BUX = os.environ.get("BUX", os.path.expanduser("~/AI Agents/BridgeUX/bux.sh"))
FILE = os.environ.get("FIGMA_FILE", "5lhRMZkLHZijqgdigjk3J1")
OUT = os.path.join(ROOT, "stories", "figma-only")
IMG = os.path.join(OUT, "img")
images_dir = sys.argv[sys.argv.index("--images") + 1] if "--images" in sys.argv else None


def bux(code, limit="2000000"):
    r = subprocess.run([BUX, "eval", "-", limit], input=code, capture_output=True, text=True,
                       cwd=os.path.dirname(BUX), env=dict(os.environ, BRIDGEUX_FILE=FILE), timeout=600)
    try:
        return json.loads(r.stdout.strip())
    except Exception:
        return None


slug = lambda s: re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")
key = lambda s: re.sub(r"[^a-z]", "", s.lower())

docs_path = os.path.join(ROOT, "build", "figma-docs.json")
docs = bux(open(os.path.join(ROOT, "pipeline", "08_figma_docs.js")).read())
if docs:
    json.dump(docs, open(docs_path, "w"), indent=1, ensure_ascii=False)
    print(f"build/figma-docs.json: {docs['count']} documentation frames, read from Figma")
else:
    docs = json.load(open(docs_path))
    print("Figma plugin did not answer: build/figma-docs.json kept as it is")

coded = {key(f[:-4]) for f in os.listdir(os.path.join(ROOT, "src", "components")) if f.endswith(".jsx")}
todo = [(n, d) for n, d in docs["docs"].items() if key(n) not in coded]
os.makedirs(IMG, exist_ok=True)
keep = set()
for name, d in todo:
    png = png_dark = None
    if images_dir:
        p = os.path.join(images_dir, d["docId"].replace(":", "_") + ".png")
        png = open(p, "rb").read() if os.path.exists(p) else None
        p = os.path.join(images_dir, d["docId"].replace(":", "_") + "-dark.png")
        png_dark = open(p, "rb").read() if os.path.exists(p) else None
    else:
        # The same frame twice: as drawn (Light) and with the Semantic collection set to Dark, put back afterwards.
        for theme in ("Light", "Dark"):
            res = bux("return (async () => { const n = await figma.getNodeByIdAsync('" + d["docId"] + "');"
                      " const col = (await figma.variables.getLocalVariableCollectionsAsync()).find(c => c.name === 'Semantic');"
                      " const before = n.explicitVariableModes[col.id];"
                      " n.setExplicitVariableModeForCollection(col, col.modes.find(m => m.name === '" + theme + "').modeId);"
                      " let b; try { b = await n.exportAsync({ format: 'PNG', constraint: { type: 'SCALE', value: 1.5 } }); }"
                      " finally { if (before) n.setExplicitVariableModeForCollection(col, before); else n.clearExplicitVariableModeForCollection(col); }"
                      " return { b: figma.base64Encode(b) }; })();", "40000000")
            data = base64.b64decode(res["b"]) if res else None
            if theme == "Light": png = data
            else: png_dark = data
    if not png:
        print(f"  no image for {name}: page left as it was")
        keep.add(slug(name))
        continue
    im = Image.open(io.BytesIO(png)).convert("RGB")
    im.save(os.path.join(IMG, slug(name) + ".jpg"), "JPEG", quality=86, optimize=True, progressive=True)
    if png_dark:
        Image.open(io.BytesIO(png_dark)).convert("RGB").save(os.path.join(IMG, slug(name) + "-dark.jpg"), "JPEG", quality=86, optimize=True, progressive=True)
    keep.add(slug(name))
    group = "Patterns" if d["chips"] and d["chips"][0] == "Pattern" else "Components"
    story = (
        "// Generated by pipeline/08_figma_docs.py from the Figma page. Do not edit by hand.\n"
        f"import img from './img/{slug(name)}.jpg';\n"
        + (f"import imgDark from './img/{slug(name)}-dark.jpg';\n" if png_dark else "")
        +         "import { FigmaOnly } from '../_shared/FigmaOnly.jsx';\n\n"
        "export default {\n"
        f"  title: {json.dumps(group + '/' + name.replace('/', '·'))},\n"
        "  component: FigmaOnly,\n"
        "  tags: ['autodocs', 'figma-only'],\n"
        f"  args: {{ name: {json.dumps(name)}, img{', imgDark' if png_dark else ''} }},\n"
        f"  parameters: {{ ds: {{ figmaName: {json.dumps(name)}, figmaOnly: true, img{', imgDark' if png_dark else ''}, figma: {json.dumps(d.get('figmaId') or d['docId'])} }} }},\n"
        "};\n\n"
        "export const Figma = {};\n"
    )
    open(os.path.join(OUT, slug(name) + ".stories.jsx"), "w").write(story)

for f in os.listdir(OUT):
    if f.endswith(".stories.jsx") and f[: -len(".stories.jsx")] not in keep:
        os.remove(os.path.join(OUT, f))
for f in os.listdir(IMG):
    base = f[: f.rfind(".")]
    if base.removesuffix("-dark") not in keep:
        os.remove(os.path.join(IMG, f))
print(f"{len(keep)} Figma-only pages in stories/figma-only/")
